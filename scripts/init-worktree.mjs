#!/usr/bin/env node

import console from 'node:console';
import { spawn, spawnSync } from 'node:child_process';
import { once } from 'node:events';
import {
  chmodSync,
  copyFileSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import net from 'node:net';
import { tmpdir } from 'node:os';
import { basename, dirname, join, resolve } from 'node:path';
import process from 'node:process';
import { setTimeout as delay } from 'node:timers/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';

const DEFAULT_API_PORT = 3102;
const DEFAULT_WEB_PORT = 5274;
const DEFAULT_CONTAINER = 'pulse-fitness-app-api-1';
const PRODUCTION_DATABASE_PATH = '/data/pulse.db';
const WORKTREE_DATABASE_RELATIVE_PATH = 'apps/api/data/pulse-worktree.db';

export const usage = `Create a fully initialized Pulse feature worktree.

Usage:
  pnpm worktree:init -- <branch> [path] [options]

Options:
  --base=<ref>         Base for a new branch (default: origin/main)
  --api-port=<port>    Use a specific API port
  --web-port=<port>    Use a specific Vite port
  --container=<name>   Production API container (default: ${DEFAULT_CONTAINER})
  --no-fetch           Do not fetch and prune origin first
  --skip-smoke         Do not prove API and web startup
  --help               Show this help
`;

const parsePort = (value, optionName) => {
  const port = Number(value);
  if (!Number.isInteger(port) || port < 1024 || port > 65535) {
    throw new Error(`${optionName} must be an integer between 1024 and 65535.`);
  }
  return port;
};

export const deriveDefaultWorktreePath = (repoRoot, branch) => {
  const slug = branch.replace(/[^a-zA-Z0-9._-]+/gu, '-').replace(/^-+|-+$/gu, '');
  if (!slug) throw new Error('Branch name does not produce a usable worktree directory name.');
  return join(dirname(repoRoot), `${basename(repoRoot)}-${slug}`);
};

export const parseArguments = (argumentsList, repoRoot, currentDirectory = process.cwd()) => {
  const positional = [];
  const options = {
    apiPort: null,
    base: 'origin/main',
    container: DEFAULT_CONTAINER,
    fetch: true,
    help: false,
    smoke: true,
    webPort: null,
  };

  for (const argument of argumentsList) {
    if (argument === '--') continue;
    if (argument === '--help' || argument === '-h') options.help = true;
    else if (argument === '--no-fetch') options.fetch = false;
    else if (argument === '--skip-smoke') options.smoke = false;
    else if (argument.startsWith('--base=')) options.base = argument.slice('--base='.length);
    else if (argument.startsWith('--container=')) {
      options.container = argument.slice('--container='.length);
    } else if (argument.startsWith('--api-port=')) {
      options.apiPort = parsePort(argument.slice('--api-port='.length), '--api-port');
    } else if (argument.startsWith('--web-port=')) {
      options.webPort = parsePort(argument.slice('--web-port='.length), '--web-port');
    } else if (argument.startsWith('-')) throw new Error(`Unknown option: ${argument}`);
    else positional.push(argument);
  }

  if (options.help) return { ...options, branch: null, worktreePath: null };
  if (positional.length < 1 || positional.length > 2) throw new Error(usage.trim());

  const branch = positional[0];
  const worktreePath = positional[1]
    ? resolve(currentDirectory, positional[1])
    : deriveDefaultWorktreePath(repoRoot, branch);

  return { ...options, branch, worktreePath };
};

export const parseWorktreePaths = (porcelainOutput) =>
  porcelainOutput
    .split('\n')
    .filter((line) => line.startsWith('worktree '))
    .map((line) => line.slice('worktree '.length));

export const readReservedPorts = (worktreePaths) => {
  const reserved = new Set();
  for (const worktreePath of worktreePaths) {
    try {
      const environment = readFileSync(join(worktreePath, '.env'), 'utf8');
      for (const name of ['PORT', 'VITE_PORT']) {
        const match = environment.match(new RegExp(`^${name}=["']?(\\d+)["']?$`, 'mu'));
        if (match) reserved.add(Number(match[1]));
      }
    } catch {
      // Worktrees without a generated environment do not reserve ports.
    }
  }
  return reserved;
};

export const renderWorktreeEnvironment = ({
  apiPort,
  databasePath,
  webPort,
}) => `# Generated by scripts/init-worktree.mjs
# This file and its production-derived database are local-only and ignored by Git.
HOST=127.0.0.1
PORT=${apiPort}
API_URL=http://127.0.0.1:${webPort}
VITE_HOST=127.0.0.1
VITE_PORT=${webPort}
VITE_API_PORT=${apiPort}
VITE_API_PROXY_TARGET=http://127.0.0.1:${apiPort}
DATABASE_URL=${JSON.stringify(databasePath)}
`;

const run = (command, argumentsList, options = {}) => {
  const result = spawnSync(command, argumentsList, {
    cwd: options.cwd,
    encoding: 'utf8',
    env: options.env ?? process.env,
    stdio: options.capture ? 'pipe' : 'inherit',
  });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    const detail = options.capture ? `\n${result.stderr || result.stdout}` : '';
    throw new Error(
      `${command} ${argumentsList.join(' ')} failed with code ${result.status}.${detail}`,
    );
  }
  return options.capture ? result.stdout.trim() : '';
};

const commandExists = (command, argumentsList) => {
  const result = spawnSync(command, argumentsList, { stdio: 'ignore' });
  return !result.error && result.status === 0;
};

const isPortAvailable = (port) =>
  new Promise((resolvePromise) => {
    const server = net.createServer();
    server.unref();
    server.once('error', () => resolvePromise(false));
    server.listen({ host: '127.0.0.1', port }, () => {
      server.close(() => resolvePromise(true));
    });
  });

const selectPort = async (requestedPort, firstCandidate, reserved) => {
  if (requestedPort !== null) {
    if (reserved.has(requestedPort) || !(await isPortAvailable(requestedPort))) {
      throw new Error(`Port ${requestedPort} is already reserved or in use.`);
    }
    return requestedPort;
  }

  for (let port = firstCandidate; port <= 65535; port += 1) {
    if (!reserved.has(port) && (await isPortAvailable(port))) return port;
  }
  throw new Error(`No available port found at or above ${firstCandidate}.`);
};

const refExists = (repoRoot, ref) =>
  spawnSync('git', ['show-ref', '--verify', '--quiet', ref], { cwd: repoRoot }).status === 0;

const createWorktree = (repoRoot, branch, worktreePath, base) => {
  if (refExists(repoRoot, `refs/heads/${branch}`)) {
    run('git', ['worktree', 'add', worktreePath, branch], { cwd: repoRoot });
    return 'existing-local';
  }

  if (refExists(repoRoot, `refs/remotes/origin/${branch}`)) {
    run('git', ['worktree', 'add', '--track', '-b', branch, worktreePath, `origin/${branch}`], {
      cwd: repoRoot,
    });
    return 'existing-remote';
  }

  run('git', ['worktree', 'add', '-b', branch, worktreePath, base], { cwd: repoRoot });
  return 'new';
};

const inspectDatabase = (databasePath) => {
  const quickCheck = run('sqlite3', [databasePath, 'PRAGMA quick_check;'], { capture: true });
  if (quickCheck !== 'ok') throw new Error(`SQLite quick_check failed: ${quickCheck}`);
  const foreignKeyViolations = Number(
    run('sqlite3', [databasePath, 'SELECT COUNT(*) FROM pragma_foreign_key_check;'], {
      capture: true,
    }),
  );
  return { foreignKeyViolations, quickCheck };
};

const snapshotProductionDatabase = (container, destinationPath) => {
  const running = run('docker', ['inspect', '--format', '{{.State.Running}}', container], {
    capture: true,
  });
  if (running !== 'true') throw new Error(`Production API container ${container} is not running.`);

  const containerSnapshot = `/tmp/pulse-worktree-${process.pid}-${Date.now()}.db`;
  try {
    run('docker', [
      'exec',
      container,
      'sqlite3',
      PRODUCTION_DATABASE_PATH,
      `.backup '${containerSnapshot}'`,
    ]);
    run('docker', ['cp', `${container}:${containerSnapshot}`, destinationPath]);
  } finally {
    spawnSync('docker', ['exec', container, 'rm', '-f', containerSnapshot], { stdio: 'ignore' });
  }
  chmodSync(destinationPath, 0o600);
  return inspectDatabase(destinationPath);
};

export const hasProcessExited = (child) => child.exitCode !== null || child.signalCode !== null;

const waitForHttp = async (url, child, deadline) => {
  while (Date.now() < deadline) {
    if (hasProcessExited(child)) {
      throw new Error(
        `Development process exited (${child.signalCode ?? `code ${child.exitCode}`}).`,
      );
    }
    try {
      const response = await fetch(url, { signal: AbortSignal.timeout(1500) });
      if (response.ok) return;
    } catch {
      // The servers are still starting.
    }
    await delay(500);
  }
  throw new Error(`Timed out waiting for ${url}.`);
};

const stopProcessGroup = async (child) => {
  if (hasProcessExited(child) || !child.pid) return;
  const gracefulExit = once(child, 'exit');
  try {
    process.kill(-child.pid, 'SIGTERM');
  } catch {
    child.kill('SIGTERM');
  }

  const stoppedGracefully = await Promise.race([
    gracefulExit.then(() => true),
    delay(5000).then(() => false),
  ]);
  if (!stoppedGracefully && !hasProcessExited(child)) {
    const forcedExit = once(child, 'exit');
    try {
      process.kill(-child.pid, 'SIGKILL');
    } catch {
      child.kill('SIGKILL');
    }
    await forcedExit;
  }
};

const smokeTest = async (worktreePath, apiPort, webPort) => {
  const child = spawn('pnpm', ['dev'], {
    cwd: worktreePath,
    detached: true,
    env: process.env,
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  let output = '';
  const capture = (chunk) => {
    output = `${output}${chunk}`.slice(-65_536);
  };
  child.stdout.on('data', capture);
  child.stderr.on('data', capture);

  try {
    const deadline = Date.now() + 90_000;
    await Promise.all([
      waitForHttp(`http://127.0.0.1:${apiPort}/health`, child, deadline),
      waitForHttp(`http://127.0.0.1:${webPort}/`, child, deadline),
    ]);
  } catch (error) {
    throw new Error(`${error instanceof Error ? error.message : error}\n\n${output.trim()}`);
  } finally {
    await stopProcessGroup(child);
  }
};

const start = async () => {
  const scriptDirectory = dirname(fileURLToPath(import.meta.url));
  const repoRoot = resolve(scriptDirectory, '..');
  const options = parseArguments(process.argv.slice(2), repoRoot);
  if (options.help) {
    console.log(usage.trim());
    return;
  }

  const {
    apiPort: requestedApiPort,
    base,
    branch,
    container,
    fetch,
    smoke,
    worktreePath,
  } = options;
  if (branch === 'main') throw new Error('Refusing to create another worktree for main.');
  run('git', ['check-ref-format', '--branch', branch], { cwd: repoRoot, capture: true });
  if (existsSync(worktreePath)) throw new Error(`Worktree path already exists: ${worktreePath}`);
  if (!commandExists('pnpm', ['--version'])) throw new Error('pnpm is required.');
  if (!commandExists('sqlite3', ['--version'])) throw new Error('sqlite3 is required.');
  if (!commandExists('docker', ['version'])) throw new Error('Docker/OrbStack is required.');

  if (fetch) run('git', ['fetch', '--prune', 'origin'], { cwd: repoRoot });
  run('git', ['rev-parse', '--verify', `${base}^{commit}`], { cwd: repoRoot, capture: true });

  const worktreePaths = parseWorktreePaths(
    run('git', ['worktree', 'list', '--porcelain'], { cwd: repoRoot, capture: true }),
  );
  const reservedPorts = readReservedPorts(worktreePaths);
  const apiPort = await selectPort(requestedApiPort, DEFAULT_API_PORT, reservedPorts);
  reservedPorts.add(apiPort);
  const webPort = await selectPort(options.webPort, DEFAULT_WEB_PORT, reservedPorts);

  const temporaryDirectory = mkdtempSync(join(tmpdir(), 'pulse-worktree-init-'));
  const temporaryDatabase = join(temporaryDirectory, 'pulse-worktree.db');
  let worktreeCreated = false;
  try {
    console.log(`Taking a consistent snapshot from ${container}...`);
    const snapshot = snapshotProductionDatabase(container, temporaryDatabase);
    console.log(
      `Snapshot verified: quick_check=${snapshot.quickCheck}, foreign-key violations=${snapshot.foreignKeyViolations}.`,
    );

    const branchState = createWorktree(repoRoot, branch, worktreePath, base);
    worktreeCreated = true;
    const databasePath = join(worktreePath, WORKTREE_DATABASE_RELATIVE_PATH);
    mkdirSync(dirname(databasePath), { recursive: true });
    copyFileSync(temporaryDatabase, databasePath);
    chmodSync(databasePath, 0o600);

    const environmentPath = join(worktreePath, '.env');
    writeFileSync(environmentPath, renderWorktreeEnvironment({ apiPort, databasePath, webPort }), {
      mode: 0o600,
    });
    chmodSync(environmentPath, 0o600);

    console.log(`Installing locked dependencies in ${worktreePath}...`);
    run('pnpm', ['install', '--frozen-lockfile'], { cwd: worktreePath });

    if (smoke) {
      console.log('Starting API and web for an isolated smoke test...');
      await smokeTest(worktreePath, apiPort, webPort);
      inspectDatabase(databasePath);
      console.log('Smoke test passed; both development servers stopped cleanly.');
    }

    console.log(`\nWorktree ready (${branchState} branch): ${worktreePath}`);
    console.log(`API: http://127.0.0.1:${apiPort}`);
    console.log(`Web: http://127.0.0.1:${webPort}`);
    console.log(`Start: cd ${JSON.stringify(worktreePath)} && pnpm dev`);
  } catch (error) {
    if (worktreeCreated) {
      console.error(`Worktree retained for inspection: ${worktreePath}`);
    }
    throw error;
  } finally {
    rmSync(temporaryDirectory, { force: true, recursive: true });
  }
};

const invokedPath = process.argv[1] ? pathToFileURL(resolve(process.argv[1])).href : '';
if (import.meta.url === invokedPath) {
  start().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  });
}
